const OUT_DIR = path.join(ROOT, 'public', 'fonts');
const MANIFEST = path.join(ROOT, 'src', 'fontManifest.js');

// One @font-face block: family, style, weight, woff2 file, unicode-range.
const FACE_RE = /@font-face\s*\{[^}]*font-family:\s*'([^']+)';[^}]*font-style:\s*(\w+);[^}]*font-weight:\s*(\d+);[^}]*src:\s*url\(\.\/files\/([^)]+\.woff2)\)[^;]*;[^}]*unicode-range:\s*([^;]+);[^}]*\}/g;

const faces = {}; // "Family|weight|style" -> { family, weight, style, subsets: [{ file, range }] }
let files = 0;
for (const cssRel of CSS_FILES) {
  const cssPath = path.join(ROOT, 'node_modules', '@fontsource', cssRel);
  const css = fs.readFileSync(cssPath, 'utf8');
  const pkg = cssRel.split('/')[0];
  let m;
  let found = 0;
  FACE_RE.lastIndex = 0;
  while ((m = FACE_RE.exec(css))) {
    const [, family, style, weight, file, range] = m;
    const key = `${family}|${weight}|${style}`;
    faces[key] = faces[key] || { family, weight: Number(weight), style, subsets: [] };
    const dest = path.join(OUT_DIR, pkg, file);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(path.join(ROOT, 'node_modules', '@fontsource', pkg, 'files', file), dest);
    files += 1;
    faces[key].subsets.push({ file: `${pkg}/${file}`, range: range.trim() });
    found += 1;
  }
  if (!found) throw new Error(`no @font-face parsed from ${cssRel} — the @fontsource CSS shape changed, update FACE_RE`);
}

const manifest = Object.values(faces).sort((a, b) => (a.family + a.weight + a.style).localeCompare(b.family + b.weight + b.style));
const header = `// GENERATED by scripts/gen-font-manifest.cjs — do not hand-edit.\n// The runtime font store (src/fontStore.js) loads faces from public/fonts/\n// on demand; this manifest is the map from (family, weight, style) to the\n// woff2 subset files. ${manifest.length} faces, ${files} files.\n`;
fs.writeFileSync(MANIFEST, `${header}export const FONT_FACES = ${JSON.stringify(manifest, null, 2)};\n`);
const totalBytes = manifest.reduce((n, f) => n + f.subsets.reduce((a, s) => a + fs.statSync(path.join(OUT_DIR, s.file)).size, 0), 0);
console.log(`font manifest: ${manifest.length} faces, ${files} woff2 files, ${(totalBytes / 1e6).toFixed(2)} MB -> ${MANIFEST} + public/fonts/`);
