// Generates the runtime font store (FB-33 / P2-28): parses the
// @fontsource CSS for every bundled face, copies its woff2 subset files
// into public/fonts/ (a build artifact — gitignored, never committed),
// and writes src/fontManifest.js, the manifest the runtime store loads
// from. The manifest is generated text and IS committed; the woff2 files
// are regenerated on every build, so the repo stays text-only.
// Usage: node scripts/gen-font-manifest.cjs   (also runs before vite in `npm run build`)
// To add a bundled font: add its CSS file to CSS_FILES below AND an
// entry to FONT_LIST in src/fonts.js.
